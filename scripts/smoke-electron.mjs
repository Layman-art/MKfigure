import { seedTestScene } from './test-scene.mjs';
import { _electron as electron } from 'playwright';
import electronPath from 'electron';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';

const root=process.cwd(),version=JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8')).version;
const out=path.join(root,'output','smoke',version);await fs.mkdir(out,{recursive:true});
const env={...process.env,MK_FIGURE_DATA_DIR:path.join(root,'.runtime','ui-smoke')};delete env.ELECTRON_RUN_AS_NODE;
const client=await electron.launch({executablePath:process.env.MK_PACKAGED_EXE||electronPath,args:process.env.MK_PACKAGED_EXE?[]:[root],env,timeout:60000});
const failures=[];let details={};
try{
  const page=await client.firstWindow();page.on('pageerror',e=>failures.push(e.message));
  await client.evaluate(({BrowserWindow})=>{const win=BrowserWindow.getAllWindows()[0];win.webContents.setBackgroundThrottling(false);win.restore();win.show();win.focus();});
  await page.getByRole('button',{name:/^新建科研图/}).waitFor({timeout:60000});
  await page.screenshot({path:path.join(out,'01-welcome.png')});
  const boot=await page.evaluate(()=>window.mkFigure.bootstrap());assert.equal(boot.references.length,3);assert.ok(boot.references.every(r=>r.previewUrl.startsWith('data:image/')));
  await seedTestScene(page);
  await page.getByRole('img',{name:'可编辑科研图预览'}).waitFor({timeout:60000});
  await page.getByRole('button',{name:'重命名',exact:true}).click();
  await page.getByRole('textbox',{name:'项目名称',exact:true}).fill('导出验证 · 离线示例');
  await page.getByRole('button',{name:'保存',exact:true}).click();
  await page.getByRole('button',{name:'重命名',exact:true}).waitFor();
  await page.screenshot({path:path.join(out,'02-editable-preview.png')});
  const current=await page.evaluate(async()=>{const b=await window.mkFigure.bootstrap();return window.mkFigure.openProject(b.projects[0].id);});
  assert.ok(current.scene.elements.length>20);assert.ok(current.qa.structuralPassed);assert.ok(current.previewPng.startsWith('data:image/png;'));
  assert.equal(current.name,'导出验证 · 离线示例');
  await client.evaluate(({dialog},directory)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[directory]});},out);
  const before=new Set(await fs.readdir(out));
  await page.getByRole('button',{name:/导出作品/}).click();await page.getByRole('button',{name:/选择文件夹并导出/}).click();
  await page.getByText('文件已导出',{exact:true}).waitFor({timeout:60000});
  await page.screenshot({path:path.join(out,'03-export.png')});
  const files=(await fs.readdir(out)).filter(f=>!before.has(f)&&f.startsWith(current.name+'-'));
  assert.deepEqual(files.map(f=>path.extname(f)).sort(),['.png','.pptx','.svg']);
  await page.locator('.format-card').filter({hasText:'SVG'}).click();
  await page.locator('.format-card').filter({hasText:'PNG'}).click();
  const beforePpt=new Set(await fs.readdir(out));
  await page.getByRole('button',{name:/选择文件夹并导出 1 种格式/}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.export-result > button').length===2);
  const pptOnly=(await fs.readdir(out)).filter(f=>!beforePpt.has(f)&&f.startsWith(current.name+'-'));
  assert.equal(pptOnly.length,1);assert.equal(path.extname(pptOnly[0]),'.pptx');
  await page.screenshot({path:path.join(out,'05-ppt-only.png')});
  await page.getByRole('button',{name:/模型与连接/}).first().click();await page.getByText('文本 / 视觉模型',{exact:true}).waitFor();
  await page.waitForFunction(()=>!document.querySelector('.dialog-footer button:last-child')?.disabled);
  assert.equal(await page.getByText('API Key',{exact:true}).count(),0);
  assert.equal(await page.getByRole('button',{name:'DeepSeek',exact:true}).count(),0);
  await page.screenshot({path:path.join(out,'04-connections.png')});
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  const direct=await page.evaluate(()=>window.mkFigure.createProject('直达复刻测试','reconstruct'));assert.equal(direct.stage,'reconstruct');assert.equal(direct.brief.language,'original');
  const sampleFile=path.join(root,'resources','references','pastel-method.png');
  await client.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},sampleFile);
  const imported=await page.evaluate(id=>window.mkFigure.importFiles(id,'target'),direct.id);assert.equal(imported.target.kind,'image');assert.ok(imported.target.previewUrl.startsWith('data:image/png'));
  const custom=await page.evaluate(id=>window.mkFigure.importFiles(id,'reference'),direct.id);assert.ok(custom.customReference);assert.equal(custom.styleId,undefined);
  let blocked=false;try{await page.evaluate(()=>window.mkFigure.renderScene('../outside',{}));}catch{blocked=true;}assert.ok(blocked);
  assert.deepEqual(failures,[]);
  details={passed:true,referenceCount:boot.references.length,exampleElements:current.scene.elements.length,renamingPersisted:true,exportFiles:files,pptOnly,codexOnlySettings:true,directReconstruction:true,customReference:true,invalidProjectBlocked:true,pageErrors:failures};
  await fs.writeFile(path.join(out,'results.json'),JSON.stringify(details,null,2));console.log(JSON.stringify(details));
}catch(error){const page=(await client.windows())[0];if(page)await page.screenshot({path:path.join(out,'failure.png')}).catch(()=>{});console.error(error);process.exitCode=1;}
finally{await client.close();}
